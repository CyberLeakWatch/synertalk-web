// Prerenders /en/index.html from index.html using the English strings in assets/app.js,
// so search engines get real English HTML at its own URL. Run with: npm run build:en
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import vm from 'node:vm';

const ROOT = '../..';
const html = readFileSync(`${ROOT}/index.html`, 'utf8');
const js = readFileSync(`${ROOT}/assets/app.js`, 'utf8');

// Extract `const perimeterDict = {...};` by brace matching and evaluate it in isolation.
function extractObject(src, marker) {
  const start = src.indexOf('{', src.indexOf(marker));
  let depth = 0, inStr = null, esc = false;
  for (let i = start; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === inStr) inStr = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') inStr = c;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return src.slice(start, i + 1);
  }
  throw new Error(`Could not extract ${marker}`);
}
const dict = vm.runInNewContext(`(${extractObject(js, 'const perimeterDict =')})`).en;

// id -> [key, isHtml] from the setTxt('id', d.key[, true]) calls
const bindings = [...js.matchAll(/setTxt\('([\w-]+)', d\.(\w+)(, true)?\)/g)].map(m => [m[1], m[2], Boolean(m[3])]);
bindings.push(['scan-btn-txt', 'scanBtnWeb', false]);

const escapeText = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Replace the inner HTML of the element carrying id="..." (matching nested tags of the same name).
function setInner(src, id, value) {
  const open = new RegExp(`<([a-zA-Z0-9]+)\\b[^>]*\\bid="${id}"[^>]*>`).exec(src);
  if (!open) return src;
  const tag = open[1];
  const tagRe = new RegExp(`<${tag}\\b[^>]*>|</${tag}>`, 'g');
  tagRe.lastIndex = open.index + open[0].length;
  let depth = 1, m;
  while ((m = tagRe.exec(src))) {
    depth += m[0].startsWith('</') ? -1 : 1;
    if (depth === 0) return src.slice(0, open.index + open[0].length) + value + src.slice(m.index);
  }
  throw new Error(`Unclosed element #${id}`);
}

let out = html;
let missing = [];
for (const [id, key, isHtml] of bindings) {
  if (!(key in dict)) { missing.push(key); continue; }
  out = setInner(out, id, isHtml ? dict[key] : escapeText(dict[key]));
}
if (missing.length) console.warn('Missing EN keys:', missing.join(', '));

const page = 'https://web.synertalk.com/en/';
const replacements = [
  ['<html lang="es"', '<html lang="en"'],
  [/<title>[^<]*<\/title>/, `<title>${escapeText(dict.title)}</title>`],
  [/<meta name="description" content="[^"]*">/, '<meta name="description" content="Check for free whether your domain can be spoofed (SPF, DMARC, DKIM, DNSSEC). DMARC and NIS2 setup in 24-48 h and expert witness reports for crypto fraud (UNE 197001 / ISO 27037).">'],
  ['<link rel="canonical" href="https://web.synertalk.com/">', `<link rel="canonical" href="${page}">`],
  ['<meta property="og:locale" content="es_ES">', '<meta property="og:locale" content="en_GB">'],
  ['<meta property="og:locale:alternate" content="en_GB">', '<meta property="og:locale:alternate" content="es_ES">'],
  ['<meta property="og:url" content="https://web.synertalk.com/">', `<meta property="og:url" content="${page}">`],
  [/<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${escapeText(dict.title)}">`],
  [/<meta property="og:description" content="[^"]*">/, '<meta property="og:description" content="Free domain spoofing scanner, DMARC/NIS2 setup and expert witness reports for crypto fraud.">'],
  [/<meta property="og:image:alt" content="[^"]*">/, '<meta property="og:image:alt" content="Synertalk: DMARC/NIS2 email security and crypto forensics">'],
];
for (const [from, to] of replacements) {
  const before = out;
  out = out.replace(from, to);
  if (out === before) throw new Error(`Replacement not applied: ${from}`);
}
out = out.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by tools/tailwind/build-en.mjs from index.html: do not edit by hand -->');

mkdirSync(`${ROOT}/en`, { recursive: true });
writeFileSync(`${ROOT}/en/index.html`, out);
console.log(`en/index.html written (${bindings.length} strings)`);
